
from flask import Flask, render_template, request, redirect, url_for, Response, flash
import pandas as pd
import numpy as np
import joblib
import os
import csv
import io
from datetime import datetime

app = Flask(__name__)
app.secret_key = os.environ.get("FLASK_SECRET_KEY", "change-this-local-dev-key")

MODEL_PATH = "student_model.pkl"
bundle = None
model = None
dataset_averages = {
    "math_score": 0,
    "reading_score": 0,
    "writing_score": 0,
}
overall_average = 0
training_rows = 0
dataset_distribution = [2, 28, 255, 517, 195]

CATEGORICAL = [
    "gender",
    "race",
    "parent_education",
    "lunch",
    "test_preparation",
]
NUMERICAL = ["math_score", "reading_score", "writing_score"]

OPTIONS = {
    "gender": ["female", "male"],
    "race": ["group A", "group B", "group C", "group D", "group E"],
    "parent_education": [
        "some high school",
        "high school",
        "some college",
        "associate's degree",
        "bachelor's degree",
        "master's degree",
    ],
    "lunch": ["standard", "free/reduced"],
    "test_preparation": ["none", "completed"],
}

records = []


def load_model():
    global bundle, model, dataset_averages, overall_average, training_rows, dataset_distribution

    if not os.path.exists(MODEL_PATH):
        raise FileNotFoundError(
            "Model not found. Run 'python train_model.py' first."
        )

    bundle = joblib.load(MODEL_PATH)

    # This file must be the dictionary generated by train_model.py.
    if not isinstance(bundle, dict) or "model" not in bundle:
        raise ValueError(
            "Invalid model file. Delete student_model.pkl and run "
            "'python train_model.py' again."
        )

    model = bundle["model"]

    if not hasattr(model, "predict"):
        raise ValueError("The saved model does not support predict().")

    dataset_averages = bundle.get("dataset_averages", dataset_averages)
    overall_average = bundle.get("overall_average", 0)
    training_rows = bundle.get("training_rows", 0)
    dataset_distribution = bundle.get("dataset_distribution", dataset_distribution)


# Attempt initial model loading at startup
try:
    load_model()
except Exception:
    pass


def dashboard_data():
    scores = [r["prediction"] for r in records]
    return {
        "records": records,
        "total_predictions": len(records),
        "average_prediction": round(float(np.mean(scores)), 2) if scores else 0,
        "highest_prediction": round(max(scores), 2) if scores else 0,
        "pass_rate": round(
            sum(s >= 40 for s in scores) * 100 / len(scores), 1
        ) if scores else 0,
    }


@app.route("/", methods=["GET"])
def index():
    stats = dashboard_data()
    return render_template(
        "index.html",
        options=OPTIONS,
        dataset_averages=dataset_averages,
        overall_average=overall_average,
        training_rows=training_rows,
        dataset_distribution=dataset_distribution,
        **stats,
        prediction=None,
        score_details=None,
        student=None,
    )


@app.route("/predict", methods=["POST"])
def predict():
    if model is None:
        try:
            load_model()
        except Exception:
            flash("Model is not loaded. Run 'python train_model.py' to generate student_model.pkl.", "error")
            return redirect(url_for("index"))

    student = {}
    try:
        for field in CATEGORICAL:
            value = request.form.get(field, "").strip()
            if value not in OPTIONS[field]:
                raise ValueError(f"Please select a valid {field.replace('_', ' ')}.")
            student[field] = value

        for field in NUMERICAL:
            raw = request.form.get(field, "").strip()
            if not raw:
                raise ValueError(f"Enter a value for {field.replace('_', ' ')}.")
            try:
                value = float(raw)
            except ValueError:
                raise ValueError(f"{field.replace('_', ' ').title()} must be a valid number between 0 and 100.")
            if not np.isfinite(value) or not 0 <= value <= 100:
                raise ValueError(f"{field.replace('_', ' ').title()} must be between 0 and 100.")
            student[field] = value

        features = pd.DataFrame([student], columns=CATEGORICAL + NUMERICAL)
        predicted = float(model.predict(features)[0])
        predicted = float(np.clip(predicted, 0, 100))

        average = round(sum(student[f] for f in NUMERICAL) / 3, 2)
        prediction = round(predicted, 2)

        score_details = [
            {
                "name": "Math",
                "score": student["math_score"],
                "dataset_average": dataset_averages.get("math_score", 0),
            },
            {
                "name": "Reading",
                "score": student["reading_score"],
                "dataset_average": dataset_averages.get("reading_score", 0),
            },
            {
                "name": "Writing",
                "score": student["writing_score"],
                "dataset_average": dataset_averages.get("writing_score", 0),
            },
        ]

        record = {
            "id": (records[0]["id"] + 1) if records else 1,
            "created_at": datetime.now().strftime("%Y-%m-%d %H:%M"),
            "prediction": prediction,
            "average": average,
            "status": "Pass" if prediction >= 40 else "Fail",
            **student,
        }
        records.insert(0, record)
        del records[500:]  # Limit local in-memory history.

        return render_template(
            "index.html",
            options=OPTIONS,
            dataset_averages=dataset_averages,
            overall_average=overall_average,
            training_rows=training_rows,
            dataset_distribution=dataset_distribution,
            **dashboard_data(),
            prediction=prediction,
            score_details=score_details,
            student=student,
        )

    except Exception as exc:
        flash(str(exc), "error")
        return redirect(url_for("index"))


@app.route("/export", methods=["GET"])
def export_csv():
    output = io.StringIO()
    fields = [
        "id", "created_at", *CATEGORICAL, *NUMERICAL,
        "average", "prediction", "status",
    ]
    writer = csv.DictWriter(output, fieldnames=fields, extrasaction="ignore")
    writer.writeheader()
    writer.writerows(records)

    return Response(
        output.getvalue(),
        mimetype="text/csv",
        headers={"Content-Disposition": "attachment; filename=edupredict_records.csv"},
    )


@app.route("/clear", methods=["POST"])
def clear_records():
    records.clear()
    flash("Prediction history cleared.", "success")
    return redirect(url_for("index"))


if __name__ == "__main__":
    try:
        load_model()
        print("EduPredict AI model loaded successfully.")
    except (OSError, ValueError, KeyError) as exc:
        print(f"MODEL ERROR: {exc}")

    port = int(os.environ.get("PORT", 5000))
    app.run(host="0.0.0.0", port=port)
